"""Runtime loader and statistical-arbitrage research utilities.

No orders are generated by this module. Pair analysis is research-only until
validated instrument pairs are explicitly configured in strategy_spec.json.
"""
import json
import math
from pathlib import Path
from statistics import mean, pstdev

DEFAULT_SPEC = Path(__file__).with_name("strategy_spec.json")


def load_strategy_spec(path=None):
    target = Path(path or DEFAULT_SPEC)
    with target.open("r", encoding="utf-8") as stream:
        spec = json.load(stream)
    if spec.get("mode", {}).get("account") != "DEMO_ONLY":
        raise ValueError("Strategy policy must remain DEMO_ONLY")
    risk = spec.get("risk", {})
    if int(risk.get("per_symbol_open_positions", 0)) != 1:
        raise ValueError("Policy must enforce one open position per symbol")
    if int(risk.get("other_successful_entries_before_symbol_reuse", 0)) < 1:
        raise ValueError("Invalid symbol rotation policy")
    return spec


def analyze_pair(prices_a, prices_b, *, min_observations=300,
                 min_abs_correlation=0.7, entry_z=2.0):
    """Estimate OLS log-price spread and return a descriptive, non-trading signal.

    Inputs must be synchronized, positive prices in oldest-to-newest order.
    This simple statistic is not a cointegration test and must not authorize orders.
    """
    n = min(len(prices_a), len(prices_b))
    if n < min_observations:
        return {"ready": False, "reason": "insufficient_synchronized_history", "observations": n}
    a = [float(x) for x in prices_a[-n:]]
    b = [float(x) for x in prices_b[-n:]]
    if any(not math.isfinite(x) or x <= 0 for x in a + b):
        return {"ready": False, "reason": "invalid_price_data", "observations": n}
    la, lb = [math.log(x) for x in a], [math.log(x) for x in b]
    ma, mb = mean(la), mean(lb)
    va = sum((x - ma) ** 2 for x in la)
    vb = sum((x - mb) ** 2 for x in lb)
    if va <= 0 or vb <= 0:
        return {"ready": False, "reason": "zero_variance", "observations": n}
    covariance = sum((x - ma) * (y - mb) for x, y in zip(la, lb))
    corr = covariance / math.sqrt(va * vb)
    if abs(corr) < min_abs_correlation:
        return {"ready": False, "reason": "correlation_below_threshold",
                "observations": n, "correlation": round(corr, 4)}
    beta = covariance / vb
    spread = [x - beta * y for x, y in zip(la, lb)]
    # Estimate z against a prior rolling window, excluding the current observation.
    baseline = spread[:-1]
    sd = pstdev(baseline)
    if sd <= 1e-12:
        return {"ready": False, "reason": "spread_variance_too_small",
                "observations": n, "correlation": round(corr, 4)}
    z = (spread[-1] - mean(baseline)) / sd
    label = "candidate_sell_spread" if z >= entry_z else (
        "candidate_buy_spread" if z <= -entry_z else "no_extreme_deviation")
    return {
        "ready": True,
        "trading_authorized": False,
        "reason": "research_only_requires_cointegration_costs_and_walk_forward",
        "observations": n,
        "correlation": round(corr, 4),
        "beta": round(beta, 6),
        "z_score": round(z, 4),
        "candidate": label
    }
